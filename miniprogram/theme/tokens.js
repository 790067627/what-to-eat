const ALIAS_MAP = {
  '--color-primary': '--color-accent',
  '--color-primary-light': '--color-accent-soft',
  '--color-primary-dark': '--color-accent-deep',
  '--color-bg': '--bg-page',
  '--color-card': '--bg-card-solid',
  '--color-text': '--text-primary',
  '--color-text-sub': '--text-secondary',
  '--color-text-hint': '--text-hint',
  '--color-border': '--border-default'
};

// 预拼 CSS 变量注入串（page-meta page-style / 组件根节点 style 共用），模块加载时缓存
Object.keys(TOKENS).forEach(name => {
  const css = TOKENS[name].css;
  Object.keys(ALIAS_MAP).forEach(alias => {
    const src = ALIAS_MAP[alias];
    if (css[src] !== undefined && css[alias] === undefined) css[alias] = css[src];
  });
  TOKENS[name].varsString = Object.keys(css).map(k => `${k}:${css[k]}`).join(';');
});

